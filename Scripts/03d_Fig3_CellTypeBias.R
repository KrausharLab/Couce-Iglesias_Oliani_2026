# ---- Load and quality-control scRNA-seq data ----
load_h5_seurat <- function(file, age) {
  h5 <- H5File$new(file, mode = "r")
  on.exit(h5$close_all(), add = TRUE)

  counts <- sparseMatrix(
    i = h5[["mm10/indices"]][] + 1L,
    p = h5[["mm10/indptr"]][],
    x = as.numeric(h5[["mm10/data"]][]),
    dims = h5[["mm10/shape"]][],
    dimnames = list(
      make.unique(h5[["mm10/gene_names"]][]),
      paste0(age, "_", h5[["mm10/barcodes"]][])
    )
  )

  object <- CreateSeuratObject(
    counts = counts,
    project = age,
    min.cells = 3,
    min.features = 200
  )
  object$age <- age
  object
}

seurat_list <- lapply(names(h5_files), function(age) {
  object <- load_h5_seurat(h5_files[[age]], age)
  object[["pct_mt"]] <- PercentageFeatureSet(object, pattern = "^mt-")
  subset(object, subset = nFeature_RNA < 6000 & pct_mt < 20)
})
names(seurat_list) <- names(h5_files)

qc_table <- bind_rows(lapply(names(seurat_list), function(age) {
  data.frame(age = age, cells_after_qc = ncol(seurat_list[[age]]))
}))



# ---- Integrate, cluster and annotate scRNA-seq data ----
combined <- merge(
  x = seurat_list[[1]],
  y = seurat_list[-1],
  add.cell.ids = names(seurat_list)
)
combined$age <- factor(combined$age, levels = age_order)

combined <- NormalizeData(combined, verbose = FALSE)
combined <- FindVariableFeatures(combined, nfeatures = 3000, verbose = FALSE)
combined <- ScaleData(combined, verbose = FALSE)
combined <- RunPCA(combined, npcs = 50, verbose = FALSE)
combined <- harmony::RunHarmony(
  combined,
  group.by.vars = "age",
  reduction.use = "pca",
  verbose = FALSE
)
combined <- FindNeighbors(combined, reduction = "harmony", dims = 1:30, verbose = FALSE)
combined <- FindClusters(combined, resolution = 0.5, verbose = FALSE)
combined <- RunUMAP(combined, reduction = "harmony", dims = 1:30, verbose = FALSE)
combined <- JoinLayers(combined)

for (celltype in names(markers)) {
  available_markers <- intersect(markers[[celltype]], rownames(combined))

  if (length(available_markers) >= 2) {
    combined <- AddModuleScore(
      combined,
      features = list(available_markers),
      name = celltype,
      ctrl = 50,
      verbose = FALSE
    )
    combined[[celltype]] <- combined[[paste0(celltype, "1")]]
    combined[[paste0(celltype, "1")]] <- NULL
  }
}

score_columns <- intersect(names(markers), colnames(combined@meta.data))
if (length(score_columns) == 0) {
  stop("No marker module scores were generated. Check marker names and gene identifiers.")
}

score_matrix <- as.matrix(combined@meta.data[, score_columns, drop = FALSE])
combined$cell_type <- score_columns[max.col(score_matrix, ties.method = "first")]
combined$cell_type[apply(score_matrix, 1, max) < 0] <- "Unknown"
combined$cell_type <- factor(combined$cell_type, levels = c(names(markers), "Unknown"))

saveRDS(combined, file.path(path, "Objects/Fig3_CellTypeBias_Seurat.rds"))

