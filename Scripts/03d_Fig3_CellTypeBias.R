# ---- Cell-type proportions ----
prop_df <- combined@meta.data %>%
  count(age, cell_type, name = "n") %>%
  group_by(age) %>%
  mutate(proportion = n / sum(n)) %>%
  ungroup() %>%
  filter(cell_type != "Unknown") %>%
  mutate(
    age = factor(age, levels = age_order),
    cell_type = factor(cell_type, levels = names(markers))
  )



# ---- Load and prepare SILAC data ----
silac <- readRDS(silac_file) %>%
  pivot_longer(
    cols = any_of(c(
      "ratios_HL", "ratios_HT", "ratios_LT", "riBAQ_H", "riBAQ_L",
      "iBAQ_H", "iBAQ_L", "LFQ_L", "LFQ_H", "LFQ_T", "H", "L", "t12"
    )),
    names_to = "Experiment",
    values_to = "Value"
  ) %>%
  mutate(Value = replace(Value, is.infinite(Value) | is.nan(Value), NA_real_)) %>%
  filter(
    !is.na(Value),
    Value > 0,
    Embryonic_Age %in% age_order,
    Incubation_Time == "4h"
  )

get_age_median <- function(experiment) {
  silac %>%
    filter(Experiment == experiment) %>%
    group_by(Embryonic_Age) %>%
    summarise(median_val = median(log2(Value), na.rm = TRUE), .groups = "drop") %>%
    mutate(Embryonic_Age = factor(Embryonic_Age, levels = age_order))
}

get_protein_age <- function(experiment) {
  silac %>%
    filter(Experiment == experiment) %>%
    group_by(genes, Embryonic_Age) %>%
    summarise(value = median(log2(Value), na.rm = TRUE), .groups = "drop") %>%
    mutate(Embryonic_Age = factor(Embryonic_Age, levels = age_order))
}

