# ---- Extended Data Figure 3b ----
# Correlation between cell-type proportions and SILAC metrics
correlation_experiments <- intersect(c("ratios_HL", "ratios_HT"), available_experiments)

prop_wide <- prop_df %>%
  select(age, cell_type, proportion) %>%
  pivot_wider(names_from = cell_type, values_from = proportion) %>%
  mutate(age = as.character(age))

silac_wide <- bind_rows(lapply(correlation_experiments, function(experiment) {
  get_age_median(experiment) %>%
    mutate(metric = unname(metric_labels[experiment]))
})) %>%
  mutate(Embryonic_Age = as.character(Embryonic_Age)) %>%
  pivot_wider(names_from = metric, values_from = median_val)

combined_wide <- left_join(
  prop_wide,
  silac_wide,
  by = c("age" = "Embryonic_Age")
)

celltype_variables <- intersect(names(markers), colnames(combined_wide))
metric_variables <- intersect(unname(metric_labels[correlation_experiments]), colnames(combined_wide))

correlation_matrix <- matrix(
  NA_real_,
  nrow = length(celltype_variables),
  ncol = length(metric_variables),
  dimnames = list(celltype_variables, metric_variables)
)
pvalue_matrix <- correlation_matrix

for (celltype in celltype_variables) {
  for (metric in metric_variables) {
    correlation_data <- combined_wide %>%
      select(all_of(c(celltype, metric))) %>%
      drop_na()

    if (nrow(correlation_data) >= 4) {
      test <- cor.test(
        correlation_data[[celltype]],
        correlation_data[[metric]],
        method = "spearman",
        exact = FALSE
      )
      correlation_matrix[celltype, metric] <- unname(test$estimate)
      pvalue_matrix[celltype, metric] <- test$p.value
    }
  }
}

rownames(correlation_matrix) <- gsub("_", " ", rownames(correlation_matrix))
rownames(pvalue_matrix) <- gsub("_", " ", rownames(pvalue_matrix))

p <- ggcorrplot(
  correlation_matrix,
  p.mat = pvalue_matrix,
  sig.level = 0.05,
  insig = "pch",
  pch = 4,
  pch.cex = 3,
  method = "square",
  lab = TRUE,
  lab_size = 3.5,
  colors = c("#2166AC", "white", "#D6604D"),
  legend.title = "rho",
  ggtheme = theme_classic(base_size = 11)
) +
  labs(
    x = NULL,
    y = NULL,
    subtitle = "X: p > 0.05; n = 5 embryonic ages"
  ) +
  theme(
    axis.text.x = element_text(angle = 35, hjust = 1, size = 10),
    axis.text.y = element_text(size = 10)
  )

